//! RSA fixtures for key size and exponent limits.
//!
//! They were generated with `openssl genpkey` (OpenSSL 3.6.4), except the 4097-bit key.
//! OpenSSL rounds 4097 bits down to 4096, so that key was made with Python's
//! `cryptography` 46.0.3.

pub(crate) struct TestKey {
    pub bits: usize,
    pub e: u64,
    pub private_pem: &'static str,
    pub public_pem: &'static str,
}

impl TestKey {
    pub fn is_allowed(&self) -> bool {
        (2048..=4096).contains(&self.bits) && self.e == 65537
    }

    pub fn is_policy_error(&self, error: &crate::JWTError, private: bool) -> bool {
        use crate::JWTError;
        match error {
            JWTError::WeakKey => self.bits < 2048,
            JWTError::UnsupportedRSAModulus => self.bits > 4096,
            JWTError::InvalidKeyPair => private && self.e != 65537,
            JWTError::InvalidPublicKey => !private && self.e != 65537,
            _ => false,
        }
    }

    /// Larger public keys fail in the pure-Rust backend before our size check.
    pub fn backend_rejects_public_key(&self) -> bool {
        cfg!(any(
            feature = "pure-rust",
            target_arch = "wasm32",
            target_arch = "wasm64"
        )) && self.bits > 4096
    }
}

pub(crate) fn key_2048() -> &'static TestKey {
    KEYS.iter()
        .find(|key| key.bits == 2048 && key.e == 65537)
        .unwrap()
}

pub(crate) fn der_from_pem(pem: &str) -> Vec<u8> {
    use ct_codecs::{Base64, Decoder};
    let b64: String = pem.lines().filter(|l| !l.starts_with("-----")).collect();
    Base64::decode_to_vec(b64, None).unwrap()
}

